"""A10 result tables -> results/summary.md (and summary.json)."""

from __future__ import annotations

import json
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent
R = HERE / "results"
ORDER = ["colmap", "prior", "prior_old", "cda3", "cpi3", "pi3", "pi3c", "da3", "vggt"]
LABEL = {"colmap": "COLMAP images only", "prior": "COLMAP + ARKit prior (3 cm)", "prior_old": "COLMAP + prior (old 0.3 m)",
         "cda3": "COLMAP poses + DA3 depth", "cpi3": "COLMAP poses + pi3 depth", "pi3": "pi3 alone", "pi3c": "pi3 + consistency",
         "da3": "DA3 alone", "vggt": "VGGT alone"}


def f(x, nd=1):
    return "–" if x is None else f"{x:.{nd}f}"


def eth_rows():
    gt = json.loads((R / "gt_c1.json").read_text()) if (R / "gt_c1.json").exists() else {}
    rows = []
    for p in sorted(R.glob("*/*/*/*.json")):
        if p.name.endswith(".scale.json") or p.parts[-4] in ("lamar", "houses"):
            continue
        r = json.loads(p.read_text())
        s = r.get("score") or {}
        kd, ob = s.get("kd") or {}, s.get("kd_observed") or {}
        comp = s.get("completeness_10cm_icp") or {}
        cov = s.get("coverage_by_rule") or {}
        g = (cov.get("ground_strip") or {})
        fp3 = next((x for x in (g.get("sensitivity") or []) if x.get("rule_id") == "footprint3in"), {})
        c1 = (r.get("c1") or {}).get("g80") or {}
        vn = Counter(v.get("kind") + (":" + v.get("band") if v.get("band") else "") for v in (c1.get("views_needed") or []))
        rows.append({"scene": r["scene"], "quality": r["quality"], "set": r["set"], "method": p.stem, "n": r["n"],
                     "reg": r.get("registered"), "kd_n": kd.get("n"), "kd_med": kd.get("median_in"), "kd_p90": kd.get("p90_in"),
                     "kd_le6": kd.get("share_le_6in"), "ob_n": ob.get("n"), "ob_med": ob.get("median_in"), "ob_p90": ob.get("p90_in"),
                     "ob_le6": ob.get("share_le_6in"), "phantom": (s.get("status") or {}).get("phantom"),
                     "meter_wall": comp.get("meter_wall"), "wall_face": comp.get("wall_face"), "ground": comp.get("ground_strip"),
                     "overhead": comp.get("overhead"), "ground_claimed_rule": g.get("claimed_by_rule"),
                     "ground_claimed_fp3": fp3.get("claimed_by_rule"), "false_obs": s.get("false_observed_claims"),
                     "scale_err": s.get("cloud_scale_error_pct") if p.stem.startswith("prior") else None,
                     "c1": c1.get("decision"), "dec": c1.get("decidable_share"), "outcomes": c1.get("outcomes"),
                     "unsure": c1.get("unsure_causes"), "views_needed": dict(vn),
                     "dec_gt": (gt.get(f"{r['scene']}.g80") or {}).get("decidable_share"),
                     "time_s": r.get("total_s"), "infer_s": r.get("infer_s"), "error": r.get("error") or r.get("score_error")})
    return rows


def main():
    rows = eth_rows()
    L = ["# A10 summary tables (generated by summarize.py)", ""]
    for q in ("dslr_ref", "combo_day"):
        L += [f"## ETH3D, images = {q}", "",
              "| scene | set | method | reg | KDs | all med / p90 in | observed n, med / p90 in | ≤6 in (obs) | phantom | meter wall / wall face / ground / overhead ≤10 cm | ground claimed (75° / fp3in) | scale err | C1 decidable (GT) | views needed |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for r in sorted([x for x in rows if x["quality"] == q], key=lambda x: (x["scene"], x["set"], ORDER.index(x["method"]) if x["method"] in ORDER else 99)):
            L.append(f"| {r['scene']} | {r['set']} | {LABEL.get(r['method'], r['method'])} | {r['reg']}/{r['n']} | {r['kd_n']} | "
                     f"{f(r['kd_med'])} / {f(r['kd_p90'])} | {r['ob_n']}, {f(r['ob_med'])} / {f(r['ob_p90'])} | {f(r['ob_le6'] and 100 * r['ob_le6'], 0)} % | {r['phantom']} | "
                     f"{f(r['meter_wall'] and 100 * r['meter_wall'], 0)} / {f(r['wall_face'] and 100 * r['wall_face'], 0)} / {f(r['ground'] and 100 * r['ground'], 0)} / {f(r['overhead'] and 100 * r['overhead'], 0)} % | "
                     f"{f(r['ground_claimed_rule'] and 100 * r['ground_claimed_rule'], 0)} / {f(r['ground_claimed_fp3'] and 100 * r['ground_claimed_fp3'], 0)} % | "
                     f"{f(r['scale_err'], 2)} | {f(r['dec'] and 100 * r['dec'], 0)} % ({f(r['dec_gt'] and 100 * r['dec_gt'], 0)} %) | "
                     f"{', '.join(f'{k}×{v}' for k, v in r['views_needed'].items()) or '–'} |" + (f" ERR {r['error'][:80]}" if r["error"] else ""))
        L.append("")
    sc = []
    for p in sorted(R.glob("*/*/*/*.scale.json")):
        d = json.loads(p.read_text())
        scene, q, st = p.parts[-4], p.parts[-3], p.parts[-2]
        for tag, v in d.items():
            kd = v["score"]["kd"]
            ob = v["score"].get("kd_observed") or {}
            c1 = v["c1"].get("g80") or {}
            sc.append(f"| {scene} | {q} | {st} | {LABEL.get(p.name.split('.')[0], p.name)} | {tag} ({100 * v['rel_err_applied']:+.1f} %) | {kd.get('n')} | "
                      f"{f(kd.get('median_in'))} / {f(kd.get('p90_in'))} | {f(ob.get('median_in'))} / {f(ob.get('p90_in'))} | "
                      f"{f(v['score'].get('cloud_scale_error_pct'), 2)} | {c1.get('decision')} {f(c1.get('decidable_share') and 100 * c1['decidable_share'], 0)} % |")
    if sc:
        L += ["## No-tool scale (A8 weak references, no homeowner action)", "",
              "| scene | images | set | method | scale | KDs | all med / p90 in | observed med / p90 in | scorer scale err % | C1 |", "|---|---|---|---|---|---|---|---|---|---|", *sc, ""]
    lam = []
    for p in sorted((R / "lamar").glob("*/*/*.json")):
        r = json.loads(p.read_text())
        k = "metric" if "metric" in r else "arkit_sim3"
        m, o = r.get(k) or {}, r.get("oracle_scale") or {}
        pl, po, ps = m.get("patch 4.57-7.92m (15-26 ft)") or {}, o.get("patch 4.57-7.92m (15-26 ft)") or {}, m.get("patch 0.5-2m (openings)") or {}
        cams = r.get("cams") or {}
        reg = (r.get("run") or {}).get("registered", r.get("registered"))
        lam.append(f"| {r['segment']} | {r['set']} | {LABEL.get(r['method'], r['method'])} | {reg}/{r['n']} ({(r.get('run') or {}).get('models', '–')} models) | "
                   f"{cams.get('gt_views_registered')}/{cams.get('gt_views')} | {k} | {f(pl.get('med_in'))} / {f(pl.get('p90_in'))} | "
                   f"{f(po.get('med_in'))} / {f(po.get('p90_in'))} | {f(ps.get('med_in'))} / {f(ps.get('p90_in'))} | {f(m.get('long_ratio_err_pct'), 2)} |"
                   + (f" ERR {r['error'][:80]}" if r.get("error") else ""))
    if lam:
        L += ["## LaMAR LIN (real phone frames, real ARKit, laser; A6 pair scorer, patches, ≤ 10 m)", "",
              "| segment | set | method | registered | GT views reg. | scale | 15–26 ft med / p90 in | 15–26 ft oracle | 0.5–2 m med / p90 in | long-pair scale err % |",
              "|---|---|---|---|---|---|---|---|---|---|", *lam, ""]
    hs = []
    for p in sorted((R / "houses").glob("*/*.json")):
        r = json.loads(p.read_text())
        c = r["colmap"]
        tr = {t: f"{sum(v)}/{len(v)}" for t, v in r["tagged_registered"].items() if v}
        ag = {m: (r.get(m) or {}).get("agreement") for m in ("pi3", "da3")}
        hs.append(f"| {r['house']} | {r['set']} | {c.get('registered')}/{r['n']} | {c.get('models')} | {tr} | "
                  + " | ".join(f"{f(a['centre_rms_pct_extent'])} % / {f(a['rot_err_median_deg'])}°" if a else "–" for a in ag.values()) + " |")
    if hs:
        L += ["## Walkaround houses (no GT)", "", "| house | set | COLMAP registered | models | tagged frames registered | pi3 vs COLMAP (centre RMS % extent / rot) | DA3 vs COLMAP |",
              "|---|---|---|---|---|---|---|", *hs, ""]
    (R / "summary.md").write_text("\n".join(L))
    (R / "summary.json").write_text(json.dumps(rows, indent=1, default=float))
    print("\n".join(L))


if __name__ == "__main__":
    main()
