"""Which photos are worth keeping? Single-photo accuracy on ETH3D against simple capture geometry.

    uv run python -m evals.frames      # after `evals.recon prepare` and the MoGe-2 run

Each photo is scored alone (MoGe-2, scaled by one taped 1 to 3 m distance, as in `evals.recon`) and
described by two things an app can measure while capturing: how far the wall is (median distance to
the scored points) and how obliquely it is seen (median angle between the viewing ray and the
wall's surface normal). Normals come from the laser scan rendered as depth, by the cross product of
neighbouring pixels. A keep-policy is scored by pooling the errors of the photos it keeps.
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np

from evals.eth3d import SCENES
from evals.pairs import evaluate_fixed, pool, results_json
from evals.recon import (
    PREDICTIONS,
    WIDTH,
    EvalSet,
    Scene,
    _height,
    cell,
    load_prediction,
    predict,
)

MODEL = "moge2"


def normals_from_depth(depth: np.ndarray, K: np.ndarray) -> np.ndarray:
    """Unit surface normals (H, W, 3) in the camera frame from a depth map; NaN where undefined.
    Oriented towards the camera (negative z component)."""
    h, w = depth.shape
    u, v = np.meshgrid(np.arange(w, dtype=np.float64), np.arange(h, dtype=np.float64))
    X = np.dstack([(u - K[0, 2]) / K[0, 0] * depth, (v - K[1, 2]) / K[1, 1] * depth, depth])
    dx = np.full_like(X, np.nan)
    dy = np.full_like(X, np.nan)
    dx[:, 1:-1] = X[:, 2:] - X[:, :-2]
    dy[1:-1] = X[2:] - X[:-2]
    n = np.cross(dx, dy)
    n /= np.linalg.norm(n, axis=2, keepdims=True)
    flip = n[..., 2] > 0
    n[flip] *= -1
    return n


def view_geometry(scene: Scene, name: str) -> tuple[float, float]:
    """Median distance (m) to the view's scored points and median incidence angle (degrees)."""
    v = scene.views[name]
    index, uv, edge = scene.visible(name)
    index, uv = index[~edge], uv[~edge]
    Xc = scene.cands[index] @ v.R_wc.T + v.t_wc
    dist = np.linalg.norm(Xc, axis=1)
    depth, K = scene.oracle_depth(name)
    n = normals_from_depth(depth.astype(np.float64), K)
    ui = np.clip(np.round(uv[:, 0]).astype(int), 0, WIDTH - 1)
    vi = np.clip(np.round(uv[:, 1]).astype(int), 0, _height(v) - 1)
    rays = Xc / dist[:, None]
    cos = np.abs(np.einsum("ij,ij->i", n[vi, ui], rays))
    ang = np.degrees(np.arccos(np.clip(cos[np.isfinite(cos)], 0, 1)))
    return float(np.median(dist)), float(np.median(ang))


def per_view(scene: Scene) -> list[dict]:
    """Each photo scored alone on its own fixed evaluation set (surface interior, all ranges)."""
    rows = []
    root = PREDICTIONS / scene.name / MODEL

    def pv(n):
        d, _, _ = load_prediction(root / f"{n}.npz")
        return d, scene.K(n), scene.views[n].cam_to_world, True

    for name in scene.views:
        ev = EvalSet(scene, name, None)
        pairs = ev.pairs["surface interior"]
        if not pairs:
            continue
        pts = predict(scene, ev, [name], pv, None)
        dist, angle = view_geometry(scene, name)
        raw = evaluate_fixed(pts, pairs, ev.refs)
        rows.append({"view": name, "distance_m": dist, "incidence_deg": angle, "raw": raw})
    return rows


# Thresholds span what the ETH3D photos cover: walls 4 to 41 m away, seen 26 to 75 degrees off
# head-on (median 42), so a stricter angle than 40 degrees would keep almost nothing.
POLICIES = {
    "every photo": lambda r: True,
    "wall within 6 m": lambda r: r["distance_m"] <= 6,
    "wall within 8 m": lambda r: r["distance_m"] <= 8,
    "wall within 12 m": lambda r: r["distance_m"] <= 12,
    "wall seen within 40 degrees of head-on": lambda r: r["incidence_deg"] <= 40,
    "wall seen more than 50 degrees off head-on": lambda r: r["incidence_deg"] > 50,
}


def main() -> None:
    ap = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    ap.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "results")
    args = ap.parse_args()
    rows = []
    for s in SCENES:
        for r in per_view(Scene(s)):
            rows.append({**r, "scene": s})
    lines = [
        "# Which photos to keep (generated by `uv run python -m evals.frames`)",
        "",
        "MoGe-2, one photo at a time, scaled by one taped 1 to 3 m distance; both ETH3D scenes "
        "pooled. |length error|, inches, median / p90.",
        "",
        "| Keep | Photos kept | 1-3 m spans | 3-10 m spans |",
        "| --- | --- | --- | --- |",
    ]
    summary = {}
    for label, keep in POLICIES.items():
        kept = [r for r in rows if keep(r)]
        if not kept:
            lines.append(f"| {label} | 0 of {len(rows)} | n/a | n/a |")
            continue
        p = pool([r["raw"] for r in kept])["one_known_distance"]
        a, b = p["1-3m"], p["3-10m"]
        summary[label] = {"kept": len(kept), "of": len(rows), "1-3m": a, "3-10m": b}
        lines.append(f"| {label} | {len(kept)} of {len(rows)} | {cell(a)} | {cell(b)} |")
    dist = np.array([r["distance_m"] for r in rows])
    ang = np.array([r["incidence_deg"] for r in rows])
    lines += [
        "",
        f"Photo geometry: median wall distance {np.median(dist):.1f} m (range {dist.min():.1f} to "
        f"{dist.max():.1f}); median incidence {np.median(ang):.0f} degrees (range {ang.min():.0f} "
        f"to {ang.max():.0f}).",
    ]
    per = [
        {k: (round(v, 2) if isinstance(v, float) else v) for k, v in r.items() if k != "raw"}
        | {"one_known_distance": pool([r["raw"]])["one_known_distance"]}
        for r in rows
    ]
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "frames.json").write_text(results_json({"policies": summary, "photos": per}))
    md = "\n".join(lines) + "\n"
    (args.out / "frames.md").write_text(md)
    print(md)


if __name__ == "__main__":
    main()
